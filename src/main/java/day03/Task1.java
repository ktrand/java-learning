package day03;

public class Task1 {

    public static void main(String[] args) {
        // Задача 1. Расставь скобки, чтобы получилось то, что в комментариях. Числа и знаки не меняй (см. урок)
        System.out.println(2 + 3 * 4);       // нужно 20
        System.out.println(10 - 4 - 3);      // нужно 9
        System.out.println(100 / 10 / 2);    // нужно 20
        System.out.println(2 + 3 * 4 - 1);   // нужно 15
        System.out.println(8 - 2 * 3 + 1);   // нужно 1
    }
}
